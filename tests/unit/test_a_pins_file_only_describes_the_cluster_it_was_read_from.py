"""`chart/values-live-pins.yaml` is applied only to the cluster it was captured from.

The file is a CAPTURE of what one cluster runs (`scripts/k3s-pins.sh`), and it is tracked in git, so it
travels to every other checkout. Applied anywhere else it names images that host never built. Measured
2026-09-23 on a fresh arm64 host: the file carried the previous host's tags for all fifteen first-party
images (`gateway:stagerunner-04d6fcda`, `lance-rest-catalog:main-c1b4d569`, ...) while `make k3s-build`
had produced `:dev`, so every first-party pod of the first install would have been ImagePullBackOff.

The identity is the `kube-system` namespace UID: stable for a cluster's life, and new on a reinstall —
which is right, because a reinstalled cluster holds none of the images the old capture named.

Driven against FAKE `helm` and `kubectl`, so the branches are exercised rather than described.
"""

from __future__ import annotations

import json
import os
import pathlib
import subprocess

import pytest


REPO = pathlib.Path(__file__).resolve().parents[2]
IMAGE_ARGS = REPO / "scripts" / "k3s-image-args.sh"
PINS_SCRIPT = REPO / "scripts" / "k3s-pins.sh"

HERE = "11111111-aaaa-4bbb-8ccc-000000000001"
ELSEWHERE = "22222222-aaaa-4bbb-8ccc-000000000002"

#: A live release deployed from a registry — the only kind of estate a pins file is layered onto.
LIVE_REGISTRY_VALUES = {"image": {"localImages": False, "repository": "localhost:5000", "tag": "dev"}}


def _fake(path: pathlib.Path, body: str) -> pathlib.Path:
    path.write_text("#!/usr/bin/env bash\n" + body, encoding="utf-8")
    path.chmod(0o755)
    return path


def _fake_kubectl(tmp: pathlib.Path, uid: str, workloads: list[dict] | None = None) -> pathlib.Path:
    """Answers the three questions the two scripts ask: the cluster's identity, whether RayClusters are
    served, and the workloads to capture."""
    listing = json.dumps({"items": workloads or []})
    return _fake(
        tmp / "kubectl",
        f"""case "$*" in
  *"namespace kube-system"*|*"ns kube-system"*) printf '%s' '{uid}' ;;
  *raycluster*) exit 1 ;;
  *"-o json"*) cat <<'JSON'
{listing}
JSON
  ;;
  *) echo "fake kubectl: unexpected $*" >&2; exit 2 ;;
esac
""",
    )


def _fake_helm(tmp: pathlib.Path, live_values: dict | None) -> pathlib.Path:
    """`helm get values rask -o json` either prints a live release's values or fails as helm does for no release."""
    if live_values is None:
        return _fake(tmp / "helm", 'echo "Error: release: not found" >&2; exit 1\n')
    return _fake(tmp / "helm", f"cat <<'JSON'\n{json.dumps(live_values)}\nJSON\n")


def _pins(tmp: pathlib.Path, header: str) -> pathlib.Path:
    path = tmp / "pins.yaml"
    path.write_text(header + 'image:\n  tags:\n    gateway: "old-host-tag"\n  digests: {}\n', encoding="utf-8")
    return path


def _image_args(tmp: pathlib.Path, *, live_values: dict | None, uid: str, pins: pathlib.Path) -> tuple[list[str], str]:
    live_out = tmp / "live.yaml"
    done = subprocess.run(  # noqa: S603
        ["bash", str(IMAGE_ARGS), str(live_out), str(pins)],
        capture_output=True,
        text=True,
        cwd=REPO,
        timeout=60,
        env={
            "PATH": os.environ["PATH"],
            "HELM": str(_fake_helm(tmp, live_values)),
            "KUBECTL": str(_fake_kubectl(tmp, uid)),
            "K3S_TAG": "dev",
        },
    )
    assert done.returncode == 0, f"k3s-image-args.sh failed: rc={done.returncode} stderr={done.stderr!r}"
    return done.stdout.split(), done.stderr


def test_a_pins_file_captured_on_ANOTHER_cluster_is_not_applied(tmp_path: pathlib.Path) -> None:
    pins = _pins(tmp_path, f"# cluster: {ELSEWHERE}\n")

    args, said = _image_args(tmp_path, live_values=LIVE_REGISTRY_VALUES, uid=HERE, pins=pins)

    assert str(pins) not in args, f"a capture of cluster {ELSEWHERE} was applied to cluster {HERE}: {args}"
    assert ELSEWHERE in said and HERE in said, f"the skip must name both clusters so the operator can see why: {said!r}"


def test_an_UNSTAMPED_pins_file_is_not_applied(tmp_path: pathlib.Path) -> None:
    """A capture that does not say where it came from cannot be shown to describe this cluster."""
    pins = _pins(tmp_path, "# GENERATED by scripts/k3s-pins.sh\n")

    args, said = _image_args(tmp_path, live_values=LIVE_REGISTRY_VALUES, uid=HERE, pins=pins)

    assert str(pins) not in args, f"an unstamped capture was applied: {args}"
    assert "make k3s-pins" in said, f"the skip must say how to produce an applicable capture: {said!r}"


def test_a_pins_file_captured_on_THIS_cluster_layers_over_the_live_release(tmp_path: pathlib.Path) -> None:
    pins = _pins(tmp_path, f"# cluster: {HERE}\n")

    args, _ = _image_args(tmp_path, live_values=LIVE_REGISTRY_VALUES, uid=HERE, pins=pins)

    live_out = str(tmp_path / "live.yaml")
    assert args == ["-f", live_out, "-f", str(pins)], f"expected the live base then this cluster's pins, got {args}"


def test_a_live_registry_release_keeps_its_own_image_mode(tmp_path: pathlib.Path) -> None:
    """The #135 invariant, driven: an estate that deploys from a registry must not be rewritten to
    side-loaded bare names, which resolve to Docker Hub and ImagePullBackOff fleet-wide."""
    pins = _pins(tmp_path, f"# cluster: {HERE}\n")

    args, _ = _image_args(tmp_path, live_values=LIVE_REGISTRY_VALUES, uid=HERE, pins=pins)

    assert "image.localImages=true" not in args, f"a live registry release was switched to side-loaded images: {args}"


def test_k3s_pins_STAMPS_the_cluster_it_read(tmp_path: pathlib.Path) -> None:
    workloads = [
        {
            "metadata": {"name": "rask-gateway"},
            "spec": {"template": {"spec": {"containers": [{"image": "localhost:5000/gateway:tag-one"}]}}},
        }
    ]
    out = tmp_path / "captured.yaml"
    done = subprocess.run(  # noqa: S603
        ["bash", str(PINS_SCRIPT), str(out)],
        capture_output=True,
        text=True,
        cwd=REPO,
        timeout=60,
        env={"PATH": os.environ["PATH"], "KUBECTL": str(_fake_kubectl(tmp_path, HERE, workloads)), "KUBECONFIG": "/dev/null"},
    )

    assert done.returncode == 0, f"k3s-pins.sh failed: {done.stderr!r}"
    assert f"# cluster: {HERE}\n" in out.read_text(encoding="utf-8"), "the capture does not record which cluster it describes"


@pytest.mark.parametrize("uid", ["", "not a uid; rm -rf /"])
def test_an_UNREADABLE_cluster_identity_applies_no_pins(tmp_path: pathlib.Path, uid: str) -> None:
    """Fail closed: when the identity cannot be read, no capture can be shown to match it."""
    pins = _pins(tmp_path, f"# cluster: {uid}\n")

    args, _ = _image_args(tmp_path, live_values=LIVE_REGISTRY_VALUES, uid=uid, pins=pins)

    assert str(pins) not in args, f"pins were applied without a readable cluster identity: {args}"


@pytest.mark.parametrize("live", [None, {"image": {"localImages": True, "tag": "dev"}}], ids=["no-release", "side-loaded-release"])
def test_pins_never_hold_a_SIDE_LOADED_estate_off_its_local_tag(tmp_path: pathlib.Path, live: dict | None) -> None:
    """A capture of this very cluster still is not applied when its images are side-loaded: `image.tags.<c>`
    beats `image.tag`, so it would hold every captured component on the tag it was captured at while
    `make k3s-build k3s-import k3s-up K3S_TAG=<new>` deployed the new build to nothing."""
    pins = _pins(tmp_path, f"# cluster: {HERE}\n")

    args, _ = _image_args(tmp_path, live_values=live, uid=HERE, pins=pins)

    assert str(pins) not in args, f"a side-loaded estate was pinned: {args}"
    assert "image.tag=dev" in args, f"a side-loaded estate must render at K3S_TAG: {args}"
